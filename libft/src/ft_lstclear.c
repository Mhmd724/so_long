#include "libft.h"

void	ft_lstclear(t_list **lst, void (*del)(void *))
{
	t_list	*temp;

	if (!lst || !del || !(*lst))
		return ;
	while (*lst)
	{
		temp = *lst;
		(del)(temp->content);
		(*lst) = temp->next;
		free(temp);
		temp = NULL;
	}
}
