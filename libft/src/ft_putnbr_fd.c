#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	char	z;

	if (n == 0)
	{
		write (fd, "0", 1);
		return ;
	}
	if (n == -2147483648)
	{
		write (fd, "-2147483648", 11);
		return ;
	}
	if (n < 0)
	{
		write (fd, "-", 1);
		n = -n;
	}
	if (n / 10 != 0)
		ft_putnbr_fd(n / 10, fd);
	z = (n % 10) + '0';
	ft_putchar_fd(z, fd);
}
