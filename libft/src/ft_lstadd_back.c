#include "libft.h"

void	ft_lstadd_back(t_list **lst, t_list *new)
{
	t_list	*temp;

	if (new)
	{
		temp = ft_lstlast(*lst);
		if (!temp)
			*lst = new;
		else
			temp->next = new;
	}
}
